#ifndef VALVE_TIMING_H
#define VALVE_TIMING_H

#include <stdint.h>
#include "tim.h"

/* =====================================================================
 * 定时开关阀时间工具 (YYMMDDHHMM)
 *
 * 协议: 10位数字 = 年(2) 月(2) 日(2) 时(2) 分(2)
 *   年/月/日为 00 表示通配:
 *     0000001230  → 每天 12:30 重复
 *     0000231230  → 每月 23 号 12:30 重复
 *     0003231230  → 每年 3 月 23 号 12:30 重复
 *     2603231230  → 2026 年 3 月 23 号 12:30 (单次)
 *     0000000000  → 每天 00:00 (合法配置, 是否动作由开关决定)
 *
 * 纯逻辑模块: 只依赖字符串与 RtcDateTime_t, 无硬件/平台耦合, 可移植复用。
 * ===================================================================== */

/* 校验 YYMMDDHHMM 合法性: 返回 1=合法, 0=非法
 * 规则: 必须10位数字; 年00-99; 月00或01-12; 日00或01-31; 时00-23; 分00-59 */
uint8_t valve_timing_time_valid(const char *t);

/* 通配+容差匹配: 返回 1=命中
 * t       : YYMMDDHHMM 字符串
 * now     : 当前日期时间
 * tol_sec : 容差(秒, 目标按"目标分钟第0秒"计, 如 30 / 5)
 * 年/月/日为00时跳过该段比较; 时分按当日秒差值 diff∈[0,tol_sec] 命中 */
uint8_t valve_timing_time_match(const char *t, const RtcDateTime_t *now, int32_t tol_sec);

#endif /* VALVE_TIMING_H */