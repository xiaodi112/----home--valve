#ifndef ZERO_CAL_H
#define ZERO_CAL_H

#include <stdint.h>

/* ==================== 零点(大气基准)管理 ====================
 * 适用: 绝压式新传感器 —— 空载读数≈当地大气压。以其为空载基准,
 *       测量值 = 传感器读数 - 基准 (表压语义, 与既有阈值/上报一致)。
 *
 * 安全设计 (工业使用):
 *   1) 上电只读不改: EEPROM 有有效基准时绝不重新采样, 避免断电重启意外校零;
 *   2) EEPROM 无有效基准时, 先用编译期默认值 ZERO_CAL_DEFAULT_PA 保证可用,
 *      再由调用方尝试一次自动采集 (采集失败则继续用默认值);
 *   3) 采集必须连续 N 次全部有效且落在大气窗口内, 否则整体放弃、不动存储;
 *   4) 双槽 + seq + CRC8 + 写后回读校验: 写入过程中掉电也不会污染已有基准。
 *
 * 触发方式只有两种: 首次上电自动采集 / 用户按键手势显式重校。
 * ============================================================ */

/* 上电调用: 读双槽并应用到传感器; 无有效基准时应用默认值并标记"未校零" */
void    zero_cal_load_apply(void);

/* 是否已从 EEPROM 读到有效基准 (0 = 正在使用默认值) */
uint8_t zero_cal_is_valid(void);

/* 当前生效的基准值 (Pa) */
int32_t zero_cal_get(void);

/* 采集并校验 (ZERO_CAL_SAMPLE_CNT 次, 间隔 ZERO_CAL_SAMPLE_MS):
 * 成功返回 1 并输出平均值; 失败返回 0 (不改变任何存储与当前基准) */
uint8_t zero_cal_capture(int32_t *out_pa);

/* 完整校准流程: 采集 → 校验 → 写双槽 → 回读 → 应用 → 重置压力变化基准
 * 返回 1=成功; 0=失败(保持原基准不变) */
uint8_t zero_cal_run(void);

/* 清除零点基准 (恢复出厂 reset 调用):
 * 双槽写 0xFF → 数据失效; 当前会话回落到默认值 ZERO_CAL_DEFAULT_PA。
 * 重启后因无有效基准, 会重新执行一次首次自动采集 (失败则继续用默认值)。 */
void    zero_cal_erase(void);

#endif /* ZERO_CAL_H */
